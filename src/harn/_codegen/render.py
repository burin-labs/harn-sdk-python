"""Assemble source-mapped Python artifacts from the closed codegen graph."""

from __future__ import annotations

from pydantic import BaseModel

from .request import CodegenIr
from .response import GeneratedArtifact, GeneratedRange
from .types import TypeRenderer, variant_identity

_HEADER = """# Generated by harn-sdk. Do not edit.
# pyright: reportUnusedImport=false
# ruff: noqa: F401,I001
# fmt: off
from __future__ import annotations

from typing import Annotated, ClassVar, Literal, TypeAlias, Union
from typing_extensions import TypeAliasType
from pydantic import BeforeValidator, ConfigDict, Field, StrictBool, StrictFloat, StrictInt, StrictStr, WrapValidator
from harn.bindings import ApplicationFailure, MISSING, WireBytes, WireDecimal, WireModel, WireSet, WireValueModel
from harn.bindings import wire_literal_validator, wire_tuple_validator
from harn._wire_depth import wire_value_depth

"""


class ArtifactBuilder:
    def __init__(self) -> None:
        self.parts: list[str] = []
        self.offset = 0
        self.mappings: list[GeneratedRange] = []

    def append(self, content: str, source: BaseModel | None = None) -> None:
        start = self.offset
        self.parts.append(content)
        self.offset += len(content.encode("utf-8"))
        if source is not None:
            self.mappings.append(
                GeneratedRange.model_validate(
                    {
                        "start": start,
                        "end": self.offset,
                        "source": source.model_dump(mode="json"),
                    }
                )
            )

    def artifact(self, path: str = "bindings.py") -> GeneratedArtifact:
        return GeneratedArtifact(
            path=path, content="".join(self.parts), source_mappings=self.mappings
        )


def render_types(ir: CodegenIr) -> GeneratedArtifact:
    renderer = TypeRenderer(ir)
    builder = ArtifactBuilder()
    builder.append(_HEADER)
    for declaration in renderer.declarations():
        builder.append(declaration.content, declaration.source)
        builder.append("\n")
    models = []
    for wire in sorted(ir.types, key=lambda wire: wire.id):
        if wire.shape.kind == "record":
            models.append(renderer.reference(wire.id))
        elif wire.shape.kind == "enum":
            models.extend(
                renderer.reference(variant_identity(wire.id, variant.id))
                for variant in wire.shape.variants
            )
    if models:
        builder.append("for _model in (" + ", ".join(models) + ",):\n")
        builder.append("    _model.model_rebuild(_types_namespace=globals())\n")
    return builder.artifact()
